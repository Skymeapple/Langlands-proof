import cypari2,sys,json,time; pari=cypari2.Pari(); pari.allocatemem(6*10**9); pari.set_real_precision(30)
pari('read("lattice.gp")')
p=int(sys.argv[1]); t=time.time()
pari(f'G4=quatgram({p}); L5=matrix(5,5,a,b, if(a==1&&b==1,2, if(a>1&&b>1, G4[a-1,b-1], 0)))')
pari('g5=genus(L5,3); R5=g5[1]; I5=g5[2]; T5_3=g5[3]; T5_5=heckemat(R5,I5,5)')
pari('g4=genus(G4,3); R4=g4[1]; I4=g4[2]; T4_3=g4[3]; T4_5=heckemat(R4,I4,5)')
print(p,'h5',pari('#R5'),'h4',pari('#R4'), time.time()-t, flush=True)
pari('C=perpcounts(R5,R4,I4)')
print('perp done', time.time()-t, flush=True)
pari('A5=vector(#R5,i,I5[i][1]); A4=vector(#R4,i,I4[i][1])')
pari(f'write("so5_{p}.gpd", [R5,I5,T5_3,T5_5,R4,I4,T4_3,T4_5,C,A5,A4])')
print(pari('[factor(charpoly(T5_3)), factor(charpoly(T4_3))]'))
