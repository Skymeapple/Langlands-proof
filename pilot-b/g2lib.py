"""Pilot B library: tag genus 2 curves over Q by which modularity theorem covers them.

Curves are given as [f, h] meaning y^2 + h(x) y = f(x). All rigorous checks rest on
PARI (genus2red, hyperellcharpoly) and on the GAP table maxsub.txt of characteristic
polynomials of the maximal subgroups of GSp4(F3) (generated by maxsub.g).
"""
import ast
import re
import cypari2

pari = cypari2.Pari()
pari.allocatemem(2 * 10**9, silent=True)

# ---------------------------------------------------------------- GSp4(F3) data
def _load_maxsub(path="maxsub.txt"):
    allcp, maxes = None, []
    for line in open(path):
        tag, rest = line.split(" ", 1)
        if tag == "ALL":
            allcp = {tuple(c) for c in ast.literal_eval(rest.strip())}
        else:
            size, rest = rest.split(" ", 1)
            i = rest.rindex("]")
            cps = {tuple(c) for c in ast.literal_eval(rest[: i + 1])}
            maxes.append((int(size), rest[i + 1:].strip(), cps))
    return allcp, maxes

import os
ALLCP, MAXES = _load_maxsub(os.path.join(os.path.dirname(os.path.abspath(__file__)), "maxsub.txt"))

# char polys low->high mod 3 of (x^2 + x + 2)^2 and (x^2 - x + 2)^2
BAD_FROB2 = {(1, 1, 2, 2, 1), (1, 2, 2, 1, 1)}

PRIMES = [int(p) for p in pari.primes(200)]


def model(fh):
    f, h = fh
    return pari(f"[{f},{h}]")


def conductor_data(fh):
    """Return (N, minimal model [f,h], bad primes) from genus2red.

    PARI 2.17 reports exponent -1 at 2 when it cannot determine the wild conductor
    exponent at 2; then N is returned as -(odd part) to flag "2-part unknown"."""
    r = pari.genus2red(model(fh))
    fa = r[1]
    bad = [int(fa[i, 0]) for i in range(int(pari.matsize(fa)[0]))]
    exps = [int(fa[i, 1]) for i in range(len(bad))]
    if -1 in exps:
        N = 1
        for q, e in zip(bad, exps):
            if e > 0:
                N *= q ** e
        return -N, r[2], bad
    return int(r[0]), r[2], bad


def charpoly(mm, p):
    """Characteristic polynomial of Frob_p on H^1 (integer coefficients, low->high)."""
    f, h = mm[0], mm[1]
    if p == 2:
        c = pari.hyperellcharpoly(pari(f"[Mod(1,2)*({f}), Mod(1,2)*({h})]"))
    else:
        c = pari.hyperellcharpoly(pari(f"Mod(1,{p})*(4*({f})+({h})^2)"))
    return [int(c.polcoef(i)) for i in range(5)]


def ap_list(mm, bad, primes=PRIMES):
    return {p: charpoly(mm, p) for p in primes if p not in bad}


# ---------------------------------------------------------------- mod 3 image
def mod3_surjective(cps):
    """Rigorous: True iff the Frobenius char polys rule out every maximal subgroup.

    cps: dict p -> char poly (integer, low->high) for good primes p != 3.
    Returns (True, witnesses) or (False, list of maximal subgroups not ruled out)."""
    seen = {tuple(c % 3 for c in cp) for p, cp in cps.items() if p != 3}
    left = [(s, d) for s, d, M in MAXES if seen <= M]
    return (not left), left


# ---------------------------------------------------------------- endomorphism heuristics
def _sqclass(n):
    """Squarefree part of a nonzero integer."""
    if n == 0:
        return 0
    return int(pari.core(n))


def galois_shape(cp, p):
    """Shape of Q(roots of the Frobenius polynomial): 'red' (D1 square: factors over Q
    into quadratics in u = x + p/x), 'D4', 'C4', 'V4'. Also returns D1's class."""
    c0, c1, c2, c3, _ = cp
    a, b = -c3, c2  # x^4 - a x^3 + b x^2 - p a x + p^2
    D1 = a * a - 4 * (b - 2 * p)
    # u-roots u1,u2 of u^2 - a u + (b-2p); D2 = (u1^2-4p)(u2^2-4p)
    s, t = a, b - 2 * p  # u1+u2, u1 u2
    D2 = t * t - 4 * p * (s * s - 2 * t) + 16 * p * p
    k1 = _sqclass(D1)
    if D1 == 0 or k1 == 1:
        return "red", k1
    k2 = _sqclass(D2)
    if D2 == 0 or k2 == 1:
        return "V4", k1
    if k2 == k1:
        return "C4", k1
    return "D4", k1


def endo_heuristic(cps):
    """Heuristic geometric endomorphism type from Frobenius polynomials (not rigorous)."""
    shapes = {p: galois_shape(cp, p) for p, cp in cps.items() if p > 2}
    kinds = [s for s, _ in shapes.values()]
    classes = {k for s, k in shapes.values() if k not in (0, 1)}
    if all(k == "red" for k in kinds):
        return "split over Q (likely E1 x E2)"
    if len(classes) == 1:
        return f"RM over Q by Q(sqrt({classes.pop()})) (GL2-type)"
    if "D4" in kinds:
        return "typical (End = Z, likely)"
    return "geometrically non-typical, End over Q likely Z (needs case analysis)"


# ---------------------------------------------------------------- Theorem A check
def theorem_A(bad, mm, cps, surj):
    """Check BCGP 2025 Theorem A hypotheses with sufficient (rigorous) tests.

    Jacobians are principally polarized, so the polarization hypothesis holds.
    (2) is certified only via good reduction at 2 (sufficient, not necessary).
    Returns (ok, reasons_failed)."""
    fails = []
    if not surj[0]:
        fails.append("mod3-not-certified-surjective:" + "|".join(d for s, d in surj[1]))
    if 2 in bad:
        fails.append("bad-at-2")
    else:
        if tuple(c % 3 for c in cps[2]) in BAD_FROB2:
            fails.append("Frob2-charpoly-excluded")
    if 3 in bad:
        fails.append("bad-at-3")
    else:
        c = cps[3]
        if c[2] % 3 == 0:
            fails.append("non-ordinary-at-3")
        P = pari(f"Pol({list(reversed(c))})")
        if not pari.issquarefree(P):
            fails.append("Frob3-repeated-roots")
    return (not fails), fails


def quad_twist(mm, d):
    """y^2 + h y = f  ~  Y^2 = 4f + h^2 ; twist by d: Y^2 = d (4f + h^2)."""
    f, h = mm[0], mm[1]
    F = pari(f"{d}*(4*({f})+({h})^2)")
    return [F, pari(0)]


def curve_str(mm):
    return f"y^2 + ({mm[1]})*y = {mm[0]}"
